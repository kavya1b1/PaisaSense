// ─────────────────────────────────────────────
// DONUT CHART
// ─────────────────────────────────────────────
function renderDonut(catTotals, total) {
  const labels = Object.keys(catTotals);
  const values = Object.values(catTotals);

  document.getElementById('donutTotal').textContent = fmt(total);

  const ctx = document.getElementById('donutChart').getContext('2d');
  new Chart(ctx, {
    type: 'doughnut',
    data: {
      labels,
      datasets: [{ data: values, backgroundColor: CHART_COLORS, borderWidth: 0, hoverOffset: 6 }],
    },
    options: {
      cutout: '68%',
      plugins: {
        legend: { display: false },
        tooltip: { callbacks: { label: ctx => ` ${ctx.label}: ₹${Number(ctx.raw).toLocaleString('en-IN')}` } },
      },
      animation: { animateRotate: true, duration: 900 },
    },
  });

  document.getElementById('catList').innerHTML = labels.map((label, i) => {
    const pct = Math.round(values[i] / total * 100);
    return `
      <div class="cat-item">
        <div class="cat-left">
          <div class="cat-dot" style="background:${CHART_COLORS[i % CHART_COLORS.length]}"></div>
          <span class="cat-name">${label}</span>
        </div>
        <div class="cat-bar-wrap">
          <div class="cat-bar" style="width:${pct}%;background:${CHART_COLORS[i % CHART_COLORS.length]}"></div>
        </div>
        <div style="text-align:right">
          <div class="cat-amount">${fmt(values[i])}</div>
          <div class="cat-pct">${pct}%</div>
        </div>
      </div>
    `;
  }).join('');
}


