// ─────────────────────────────────────────────
// BUDGET VS ACTUAL
// ─────────────────────────────────────────────
function renderBudget(budget) {
  const rows = Object.entries(budget).map(([cat, vals]) => {
    const actual      = vals.actual || 0;
    const recommended = vals.recommended || 1;
    const pct         = Math.round((actual / recommended) * 100);
    const over        = actual > recommended;
    const diff        = Math.abs(pct - 100);
    const diffLabel   = over ? `⚠️ ${diff}% over budget` : `✅ ${diff}% under budget`;

    return `
      <div class="budget-row">
        <div class="budget-row-head">
          <span class="budget-cat-name">${cat}</span>
          <div style="display:flex;align-items:center;gap:10px;">
            <span class="budget-amounts">${fmt(actual)} / ${fmt(Math.round(recommended))}</span>
            <span class="budget-pct-badge ${over ? 'over' : 'under'}">${diffLabel}</span>
          </div>
        </div>
        <div class="budget-bar-wrap">
          <div class="budget-bar ${over ? 'over-budget' : 'under-budget'}" style="width:${Math.min(pct, 100)}%"></div>
        </div>
      </div>
    `;
  });

  document.getElementById('budgetBox').innerHTML = `<div class="budget-grid">${rows.join('')}</div>`;
}


