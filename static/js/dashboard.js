// TREND CHART
// ─────────────────────────────────────────────
function renderTrend(trend) {
  const labels = Object.keys(trend).slice(-14);
  const values = labels.map(k => trend[k]);

  const ctx  = document.getElementById('trendChart').getContext('2d');
  const grad = ctx.createLinearGradient(0, 0, 0, 200);
  grad.addColorStop(0, 'rgba(37,99,235,.25)');
  grad.addColorStop(1, 'rgba(37,99,235,0)');

  new Chart(ctx, {
    type: 'line',
    data: {
      labels,
      datasets: [{
        data: values, borderColor: '#2563eb', backgroundColor: grad,
        borderWidth: 2, fill: true, tension: 0.4, pointRadius: 3, pointBackgroundColor: '#2563eb',
      }],
    },
    options: {
      responsive: true, maintainAspectRatio: false,
      plugins: { legend: { display: false } },
      scales: {
        x: { grid: { display: false }, ticks: { font: { size: 10 }, maxRotation: 45 } },
        y: {
          grid: { color: '#f0f0f8' },
          ticks: { font: { size: 10 }, callback: v => '₹' + (v >= 1000 ? (v / 1000).toFixed(1) + 'k' : v) },
        },
      },
    },
  });
}


