function fmt(n) {
  return '₹' + Number(n).toLocaleString('en-IN', { maximumFractionDigits: 0 });
}


// ─────────────────────────────────────────────
// RENDER DASHBOARD
// ─────────────────────────────────────────────
function renderDashboard(data) {
  const { summary, category_totals, behavior, prediction, decisions, daily_trend } = data;

  // Risk alert banner
  if (data.risk_alert) {
    document.getElementById('riskAlertText').textContent = data.risk_alert;
    document.getElementById('riskAlertBanner').classList.add('show');
  }

  document.getElementById('dateBadge').textContent =
    `${summary.date_range_days} days analyzed · ${summary.num_transactions} transactions`;

  // Smart highlight box
  const topCat       = summary.top_category;
  const topCatAmount = data.category_totals?.[topCat] || 0;
  const topCatPct    = summary.total_spent > 0
    ? Math.round((topCatAmount / summary.total_spent) * 100)
    : 0;
  let highlightContent = topCatPct > 0
    ? `⚠️ ${topCat} accounts for ${topCatPct}% of your spending — consider optimizing this to improve savings.`
    : '⚡ ' + data.highlight;

  if (data.budget_alert) {
    highlightContent += `<br><span style="font-size:.85rem;opacity:.85;margin-top:6px;display:block;">🍔 ${data.budget_alert}</span>`;
  }
  if (data.yearly_spend) {
    highlightContent += `<br><span style="font-size:.85rem;opacity:.85;margin-top:4px;display:block;">📅 At this rate → ${fmt(data.yearly_spend)}/year</span>`;
  }
  document.getElementById('highlightBox').innerHTML = highlightContent;

  renderSummaryCards(summary, prediction);
  renderDonut(category_totals, summary.total_spent);
  renderTrend(daily_trend);
  renderBehavior(behavior);
  renderDecisions(decisions);
  renderSubscriptions(data.subscriptions);
  renderBudget(data.budget_comparison);

  // Reveal voice section and mic button
  document.getElementById('micBtn').style.display          = 'inline-flex';
  document.getElementById('voiceInputSection').style.display = 'block';

  // Auto-generate AI insights after page renders
  setTimeout(() => generateAI(), 800);
}


