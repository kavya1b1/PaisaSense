// ─────────────────────────────────────────────
// TEXT CLEANING (strip emojis/symbols for TTS)
// ─────────────────────────────────────────────
function cleanTextForSpeech(text) {
  return text
    .replace(/[\u{1F300}-\u{1FFFF}]/gu, '')
    .replace(/[⚠️✅❌💡📊🎯🔴🟡🟢⚡📅💸🔢🏆↺→←]/g, '')
    .replace(/\s+/g, ' ')
    .trim();
}


// ─────────────────────────────────────────────
// VOICE SELECTION
// ─────────────────────────────────────────────
function pickVoice(isHindi) {
  const voices = window.speechSynthesis.getVoices();
  if (isHindi) {
    const preferred = ['Google हिन्दी', 'Microsoft Heera', 'Google Hindi'];
    for (const name of preferred) {
      const match = voices.find(v => v.name === name);
      if (match) return match;
    }
    return voices.find(v => v.lang === 'hi-IN' || v.lang.startsWith('hi')) || null;
  } else {
    const preferred = ['Google हिन्दी', 'Microsoft Heera - English (India)', 'Google UK English Female'];
    for (const name of preferred) {
      const match = voices.find(v => v.name === name);
      if (match) return match;
    }
    return voices.find(v => v.lang === 'en-IN') || null;
  }
}


// ─────────────────────────────────────────────
// SPEAK — shared TTS helper
// ─────────────────────────────────────────────
function speakText(rawText, onDone) {
  window.speechSynthesis.cancel();

  const isHindi   = currentLang === 'hi' || currentLang === 'hi-en';
  const cleanText = cleanTextForSpeech(rawText);
  const utter     = new SpeechSynthesisUtterance(cleanText);
  utter.lang  = isHindi ? 'hi-IN' : 'en-IN';
  utter.rate  = 0.88;
  utter.pitch = 1.0;

  const setVoiceAndSpeak = () => {
    const voice = pickVoice(isHindi);
    if (voice) utter.voice = voice;
    if (onDone) utter.onend = onDone;
    window.speechSynthesis.speak(utter);
  };

  if (window.speechSynthesis.getVoices().length === 0) {
    window.speechSynthesis.onvoiceschanged = setVoiceAndSpeak;
  } else {
    setVoiceAndSpeak();
  }

  return utter;
}


// ─────────────────────────────────────────────
// VOICE OUTPUT (AI analysis playback)
// ─────────────────────────────────────────────
function syncVoiceButtons() {
  const playBtn = document.getElementById('voiceBtn');
  const stopBtn = document.getElementById('stopVoiceBtn');
  if (!playBtn || !stopBtn) return;

  if (isSpeaking) {
    playBtn.innerHTML = '🔊 Playing...';
    playBtn.classList.add('speaking');
    stopBtn.style.display = 'inline-flex';
  } else {
    playBtn.innerHTML = '🔊 Play';
    playBtn.classList.remove('speaking');
    stopBtn.style.display = 'none';
  }
}

function stopVoice() {
  window.speechSynthesis.cancel();
  isSpeaking = false;
  syncVoiceButtons();
}

function toggleVoice() {
  if (isSpeaking) { stopVoice(); return; }
  const text = window._aiText || document.getElementById('aiText')?.innerText;
  if (!text) return;

  isSpeaking = true;
  syncVoiceButtons();
  speakText(text, () => {
    isSpeaking = false;
    syncVoiceButtons();
  });
}


// ─────────────────────────────────────────────
// VOICE QUERY (mic input → AI answer)
// ─────────────────────────────────────────────
function startVoiceQuery() {
  const SpeechRecognition = window.SpeechRecognition || window.webkitSpeechRecognition;
  if (!SpeechRecognition) {
    alert('Voice input not supported in this browser. Please use Chrome.');
    return;
  }

  const startBtn    = document.getElementById('startVoiceBtn');
  const micBtn      = document.getElementById('micBtn');
  const indicator   = document.getElementById('listeningIndicator');
  const recognition = new SpeechRecognition();

  recognition.lang           = (currentLang === 'hi' || currentLang === 'hi-en') ? 'hi-IN' : 'en-IN';
  recognition.continuous     = false;
  recognition.interimResults = false;

  const setListening = (on) => {
    if (on) {
      startBtn.disabled = true;
      startBtn.classList.add('listening');
      document.getElementById('voiceBtnLabel').textContent = 'Listening...';
      indicator.style.display = 'flex';
      if (micBtn) { micBtn.innerHTML = '🔴 Listening...'; micBtn.disabled = true; }
    } else {
      startBtn.disabled = false;
      startBtn.classList.remove('listening');
      document.getElementById('voiceBtnLabel').textContent = 'Start Speaking';
      indicator.style.display = 'none';
      if (micBtn) { micBtn.innerHTML = '🎤 Ask'; micBtn.disabled = false; }
    }
  };

  setListening(true);
  recognition.start();

  recognition.onresult = async (event) => {
    const userQuery   = event.results[0][0].transcript;
    setListening(false);

    const queryBox    = document.getElementById('voiceQueryBox');
    const queryResult = document.getElementById('voiceQueryResult');
    queryBox.style.display = 'block';
    queryResult.className  = 'voice-response-wrap';
    queryResult.innerHTML  = `
      <div class="vr-query">You asked: "${userQuery}"</div>
      <div style="color:var(--ink-soft);font-size:.88rem;">⏳ Thinking...</div>
    `;

    try {
      const res  = await fetch('/voice-query', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ query: userQuery, language: currentLang, context: currentData }),
      });
      const data = await res.json();
      if (data.error) throw new Error(data.error);

      queryResult.innerHTML = `
        <div class="vr-query">You asked: "${userQuery}"</div>
        ${formatVoiceResponse(data.answer)}
      `;
      queryResult.classList.add('highlight-in');
      setTimeout(() => queryResult.classList.remove('highlight-in'), 700);
      speakText(data.answer);

    } catch (e) {
      queryResult.innerHTML = `
        <div class="vr-query">You asked: "${userQuery}"</div>
        <div style="color:var(--red);">⚠️ ${e.message || 'Could not process voice query.'}</div>
      `;
    }
  };

  recognition.onerror = (e) => { setListening(false); console.error('Speech recognition error:', e.error); };
  recognition.onend   = ()  => { setListening(false); };
}


// ─────────────────────────────────────────────
// FORMAT VOICE RESPONSE into labeled blocks
// ─────────────────────────────────────────────
function formatVoiceResponse(text) {
  const labels  = ['📊 Summary', '💡 Suggestion', '🎯 Impact'];
  const numbered = text.match(/\d\.\s.+?(?=\d\.|$)/gs);

  if (numbered && numbered.length >= 2) {
    return numbered.map((chunk, i) => `
      <div class="vr-block">
        <div class="vr-label">${labels[i] || `Point ${i + 1}`}</div>
        <div class="vr-text">${chunk.replace(/^\d\.\s*/, '').trim()}</div>
      </div>
    `).join('');
  }

  const sentences = text.split(/(?<=[.!?])\s+/).filter(s => s.trim().length > 10);
  if (sentences.length >= 3) {
    return sentences.slice(0, 3).map((s, i) => `
      <div class="vr-block">
        <div class="vr-label">${labels[i]}</div>
        <div class="vr-text">${s.trim()}</div>
      </div>
    `).join('');
  }

  return `<div class="vr-text">${text.replace(/\n/g, '<br>')}</div>`;
}
